package com.farmatodo.challenge.customer.infrastructure.out.persistence;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.when;

import java.time.Instant;
import java.util.Optional;
import java.util.UUID;

import com.farmatodo.challenge.customer.domain.Customer;
import com.farmatodo.challenge.customer.domain.CustomerPorts.DuplicateCustomerException;

import org.junit.jupiter.api.Test;
import org.springframework.dao.DataIntegrityViolationException;

class JpaCustomerRepositoryTest {

    @Test
    void translatesUniqueViolationsByConstraintName() {
        assertThat(JpaCustomerRepository.translate(violation("duplicate key value violates unique constraint \"uq_customers_email\"")))
                .isInstanceOf(DuplicateCustomerException.class)
                .hasFieldOrPropertyWithValue("code", "EMAIL_ALREADY_EXISTS");
        assertThat(JpaCustomerRepository.translate(violation("... \"uq_customers_phone\"")))
                .hasFieldOrPropertyWithValue("code", "PHONE_ALREADY_EXISTS");
    }

    @Test
    void unknownViolationsAreRethrownAsIs() {
        DataIntegrityViolationException other = violation("fk_something");
        assertThat(JpaCustomerRepository.translate(other)).isSameAs(other);
    }

    CustomerJpaRepository springData = mock(CustomerJpaRepository.class);
    JpaCustomerRepository adapter = new JpaCustomerRepository(springData);
    UUID id = UUID.randomUUID();
    Customer ana = new Customer(id, "Ana", "Pérez", "ana@mail.com", "+584121234567", "Calle 1", "{bcrypt}h",
            Instant.parse("2026-11-08T10:00:00Z"));

    @Test
    void saveMapsBothWaysAndTranslatesDuplicates() {
        when(springData.saveAndFlush(any())).thenAnswer(inv -> inv.getArgument(0));
        assertThat(adapter.save(ana)).usingRecursiveComparison().ignoringFields("id").isEqualTo(ana);   // the id is generated by the database

        when(springData.saveAndFlush(any())).thenThrow(violation("\"uq_customers_phone\""));
        assertThatThrownBy(() -> adapter.save(ana)).isInstanceOf(DuplicateCustomerException.class);
    }

    @Test
    void lookupsDelegateToSpringData() {
        CustomerJpaEntity row = CustomerJpaEntity.from(ana);
        when(springData.findById(id)).thenReturn(Optional.of(row));
        when(springData.findByEmail("ana@mail.com")).thenReturn(Optional.of(row));
        when(springData.existsByEmail("ana@mail.com")).thenReturn(true);
        when(springData.existsByPhone("+584121234567")).thenReturn(true);
        when(springData.existsById(id)).thenReturn(true);

        assertThat(adapter.findById(id)).get().extracting(Customer::email).isEqualTo("ana@mail.com");
        assertThat(adapter.findByEmail("ana@mail.com")).get().extracting(Customer::phone).isEqualTo("+584121234567");
        assertThat(adapter.existsByEmail("ana@mail.com")).isTrue();
        assertThat(adapter.existsByPhone("+584121234567")).isTrue();
        assertThat(adapter.existsById(id)).isTrue();
    }

    private static DataIntegrityViolationException violation(String message) {
        return new DataIntegrityViolationException("wrapper", new RuntimeException(message));
    }
}
